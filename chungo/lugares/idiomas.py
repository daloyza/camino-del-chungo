def idioma_de(request):
    """Idioma elegido por el visitante (español si no ha elegido)."""
    idioma = request.session.get("idioma", IDIOMA_POR_DEFECTO)
    return idioma if idioma in IDIOMAS else IDIOMA_POR_DEFECTO


def textos_del_idioma(request):
    """Procesador de contexto: deja los textos disponibles en todas las plantillas como {{ t.clave }}."""
    idioma = idioma_de(request)
    return {
        "t": TEXTOS[idioma],
        "idioma": idioma,
        "idioma_html": IDIOMAS[idioma][1],
        "idiomas": [(codigo, datos[0]) for codigo, datos in IDIOMAS.items()],
    }
